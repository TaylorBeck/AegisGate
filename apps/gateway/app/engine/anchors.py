def _assert_anchor_catalog() -> None:
    seen: set[str] = set()
    if set(ANCHORS) != set(Tier):
        raise RuntimeError("anchors must cover every tier")
    for tier, rows in ANCHORS.items():
        if len(rows) != 50:
            raise RuntimeError(f"{tier.value} must have 50 anchors")
        for row in rows:
            if row in seen:
                raise RuntimeError(f"duplicate anchor: {row}")
            seen.add(row)
    if len(seen) != 150:
        raise RuntimeError("expected 150 unique anchors")


_assert_anchor_catalog()
